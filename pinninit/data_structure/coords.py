from __future__ import annotations

from dataclasses import field, make_dataclass
from typing import TYPE_CHECKING, Any, ClassVar

import torch

from ..geometry.coordinate_system import CoordSystem
from ..geometry.domain import Domain


class Coords:
    """
    Base class for the Coords dataclasses built by make_coords_dataclass.

    Each generated class has one tensor field per coordinate label, so instances
    can only be created with exactly those coordinates. Instances are frozen.
    """

    __slots__ = ()

    # Fixed for each generated class
    coord_labels: ClassVar[tuple[str, ...]]
    geometric_labels: ClassVar[tuple[str, ...]]
    internal_labels: ClassVar[tuple[str, ...]]
    coord_system: ClassVar[CoordSystem]
    device: ClassVar[torch.device]

    # Set in __post_init__
    n_points: int
    tensor: torch.Tensor
    geometric: torch.Tensor
    internal: torch.Tensor

    # Set by get_batch, None for a full set of coords
    parent: Coords | None
    parent_idx: torch.Tensor | None

    if TYPE_CHECKING:
        # The real __init__ is generated by make_dataclass
        def __init__(self, **coords: torch.Tensor) -> None: ...

    def __post_init__(self) -> None:
        self._validate_inputs()
        self._set_tensors()

    @property
    def dtype(self) -> torch.dtype:
        return self.tensor.dtype

    def get_coord(self, label: str) -> torch.Tensor:
        if label not in self.coord_labels:
            raise KeyError(f"Coordinate label '{label}' not found in coords")
        coord: torch.Tensor = getattr(self, label)
        return coord

    def get_batch(self, idx: torch.Tensor) -> Coords:
        """Get the points at idx as a new Coords object, linked to this one.

        The batch coordinates are new leaf tensors, so derivatives can be taken
        with respect to them.
        """
        if idx.dtype != torch.long:
            raise TypeError("idx must be an integer tensor of dtype torch.long")
        if idx.ndim != 1:
            raise ValueError("idx must be 1D")
        idx = idx.to(self.device)

        batch = type(self)(
            **{
                label: self.get_coord(label)[idx].detach().requires_grad_(True)
                for label in self.coord_labels
            }
        )
        object.__setattr__(batch, "parent", self)
        object.__setattr__(batch, "parent_idx", idx)
        return batch

    def is_ancestor_of(self, other: Coords) -> bool:
        """Return True if self is other, or other is a batch derived from self."""
        if other is self:
            return True
        if other.parent is None:
            return False
        return self.is_ancestor_of(other.parent)

    def indices_in(self, root: Coords) -> torch.Tensor | None:
        """Indices of these points within root, or None if self is root."""
        if self is root:
            return None
        if self.parent is None or self.parent_idx is None:
            raise ValueError(
                "Coords must be the root coords or a batch derived from them."
            )
        parent_indices = self.parent.indices_in(root)
        if parent_indices is None:
            return self.parent_idx
        return parent_indices[self.parent_idx]

    def validate_in_domain(self, domain: Domain) -> None:
        """Verify that all points are within a domain."""
        if domain.coord_system != self.coord_system:
            raise ValueError(
                f"Domain coordinate system {domain.coord_system} does not "
                f"match {self.coord_system}"
            )

        mask = domain.contains_geometric(self.geometric)
        if not torch.all(mask):
            raise ValueError("Geometric coordinates lie outside of domain.")

    def _set_tensors(self) -> None:
        """
        Store coords tensor, geometric coords tensor, and internal coords tensor.

        The order here is important since we want the computational graph to go like:
        `individual coords -> geometric -> internal`
        so that we can differentiate internal wrt both geometric and individual coords.
        """
        coords_dict = {label: self.get_coord(label) for label in self.coord_labels}
        tensor = torch.stack(list(coords_dict.values()), dim=1)

        # Stack geometric coords, then slice back so the graph goes through geometric
        geometric = torch.stack(
            [coords_dict[label] for label in self.geometric_labels], dim=1
        )
        geometric_dict = {
            label: geometric[:, i] for i, label in enumerate(self.geometric_labels)
        }

        # Internal coords are the non-geometric coords plus the internal geometric
        # coords given by the coordinate system
        internal_dict = {
            label: coord
            for label, coord in coords_dict.items()
            if label not in self.geometric_labels
        }
        internal_dict.update(
            self.coord_system.map_geometric_to_internal_geometric(geometric_dict)
        )
        internal = torch.stack(
            [internal_dict[label] for label in self.internal_labels], dim=1
        )

        # object.__setattr__ is needed because the dataclass is frozen
        object.__setattr__(self, "tensor", tensor)
        object.__setattr__(self, "geometric", geometric)
        object.__setattr__(self, "internal", internal)
        object.__setattr__(self, "n_points", tensor.shape[0])

    def _validate_inputs(self) -> None:
        lengths = []
        dtypes = set()
        for label in self.coord_labels:
            coord = self.get_coord(label)

            if not coord.is_floating_point():
                raise TypeError(
                    f"Coordinate {label} must be floating point, got {coord.dtype}"
                )
            dtypes.add(coord.dtype)

            if coord.dim() != 1:
                raise ValueError(
                    f"Coordinate {label} must be 1D, got shape {coord.shape}"
                )

            if coord.device != self.device:
                raise ValueError(
                    f"Coordinate {label} on {coord.device}, expected {self.device}"
                )

            lengths.append(coord.size(0))

        if len(set(lengths)) > 1:
            raise ValueError(
                f"All coordinates must have the same length, got {lengths}"
            )
        if len(dtypes) > 1:
            raise ValueError(f"All coordinates must have the same dtype, got {dtypes}")


def check_labels_not_reserved(labels: tuple[str, ...], base: type) -> None:
    """Labels become attribute names, so they must not shadow attributes of base."""
    reserved = set(dir(base)) | set(base.__annotations__)
    clashes = sorted(set(labels) & reserved)
    if clashes:
        raise ValueError(f"Labels {clashes} are reserved names on {base.__name__}")


def make_coords_dataclass(
    coord_labels: set[str],
    coord_system: CoordSystem,
    device: torch.device,
) -> type[Coords]:
    """The Coords class for coords with the given labels on coord_system.

    coord_labels must include the coord system's geometric axes. Any other
    labels (e.g. time) are non-geometric coords.
    """
    # Normalise device so it matches realised tensor devices ("cuda" -> "cuda:0")
    device = torch.empty(0, device=device).device
    coord_labels_sorted = tuple(sorted(coord_labels))

    if not coord_labels_sorted:
        raise ValueError("coord_labels must not be empty")

    # The coord system's tensors are combined with the coordinates
    coord_system_device = torch.empty(0, device=coord_system.device).device
    if coord_system_device != device:
        raise ValueError(
            f"coord_system is on {coord_system_device}, but the coords are on {device}"
        )

    geometric_labels = coord_system.axes_labels_selected
    if not set(geometric_labels).issubset(coord_labels_sorted):
        raise ValueError(
            f"coord_system requires geometric axes {geometric_labels} "
            f"but coord_labels only contains {set(coord_labels_sorted)}"
        )

    check_labels_not_reserved(coord_labels_sorted, Coords)

    non_geometric_labels = [
        label for label in coord_labels_sorted if label not in geometric_labels
    ]
    internal_labels = tuple(
        sorted([*non_geometric_labels, *coord_system.internal_geometric_labels])
    )

    dataclass_fields: list[tuple[str, Any, Any]] = [
        *((label, torch.Tensor, field()) for label in coord_labels_sorted),
        ("n_points", int, field(init=False)),
        ("tensor", torch.Tensor, field(init=False)),
        ("geometric", torch.Tensor, field(init=False)),
        ("internal", torch.Tensor, field(init=False)),
        ("parent", Coords | None, field(init=False, default=None)),
        ("parent_idx", torch.Tensor | None, field(init=False, default=None)),
    ]
    class_constants = {
        "coord_labels": coord_labels_sorted,
        "geometric_labels": geometric_labels,
        "internal_labels": internal_labels,
        "coord_system": coord_system,
        "device": device,
    }

    return make_dataclass(
        "Coords",
        dataclass_fields,
        bases=(Coords,),
        namespace=class_constants,
        frozen=True,
        eq=False,
        slots=True,
    )
