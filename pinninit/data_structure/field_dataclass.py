from __future__ import annotations

from dataclasses import field, make_dataclass
from itertools import product
from typing import TYPE_CHECKING, Any, ClassVar

import torch

from .coords_dataclass import Coords, check_labels_not_reserved


class Field:
    """
    Base class for the Field dataclasses built by make_field_dataclass.

    Each generated class is for one Coords class and one tensor rank, and has
    one tensor field per component. A Field instance holds values at the points
    of its coords, each component of shape (n_points,).

    Methods taking coords accept the field's coords or any batch derived from
    them, and read or write only the rows belonging to those coords.
    """

    __slots__ = ()

    # Fixed for each generated class
    coords_class: ClassVar[type[Coords]]
    rank: ClassVar[int]
    component_labels: ClassVar[tuple[str, ...]]

    label: str
    coords: Coords

    if TYPE_CHECKING:
        # The real __init__ is generated by make_dataclass
        def __init__(
            self, label: str, coords: Coords, **components: torch.Tensor
        ) -> None: ...

    def __post_init__(self) -> None:
        if type(self.coords) is not self.coords_class:
            raise TypeError(
                f"Field coords must be an instance of {self.coords_class.__name__} "
                f"with coord labels {self.coords_class.coord_labels}"
            )

        # Components that were not given start as zeros
        for label in self.component_labels:
            if getattr(self, label) is None:
                zeros = torch.zeros(
                    self.coords.n_points, dtype=self.coords.dtype, device=self.device
                )
                setattr(self, label, zeros)
        self._validate_inputs()

    @property
    def device(self) -> torch.device:
        return self.coords_class.device

    @property
    def dtype(self) -> torch.dtype:
        component: torch.Tensor = getattr(self, self.component_labels[0])
        return component.dtype

    def get_component(self, label: str, coords: Coords | None = None) -> torch.Tensor:
        """A single component, shape (n_points,)."""
        if label not in self.component_labels:
            raise KeyError(f"Component label '{label}' not found in field components")
        component: torch.Tensor = getattr(self, label)
        indices = self._indices(coords)
        return component if indices is None else component[indices]

    def component_tensor(self, coords: Coords | None = None) -> torch.Tensor:
        """
        Field values arranged in tensor of shape (n_points, n_components).
        Useful for e.g. component-wise comparisons.

        Note: scalar fields have shape (n_points, 1).
        """
        return torch.stack(
            [self.get_component(label, coords) for label in self.component_labels],
            dim=1,
        )

    def tensor(self, coords: Coords | None = None) -> torch.Tensor:
        """
        Field values arranged in tensor of shape
        (n_points, n_geometric, ..., n_geometric). Useful for e.g. linear algebra.

        Note: scalar fields have shape (n_points,).
        """
        coords = self.coords if coords is None else coords
        return self.component_tensor(coords).reshape(tensor_shape(coords, self.rank))

    def update_from_component_dict(
        self,
        new_components: dict[str, torch.Tensor],
        coords: Coords | None = None,
        detach_stale_values: bool = True,
        detach_new_values: bool = False,
    ) -> None:
        """Update field from dict of components in form
        dict[component label: tensor with shape (n_points,)]
        """
        if set(new_components) != set(self.component_labels):
            raise KeyError(
                "New components must contain all field component labels when "
                "updating field"
            )

        n_points = (self.coords if coords is None else coords).n_points
        for label, tensor in new_components.items():
            if tensor.shape != (n_points,):
                raise ValueError(
                    f"Component '{label}' has shape {tensor.shape}, "
                    f"expected ({n_points},)"
                )

        new_tensor = torch.stack(
            [new_components[label] for label in self.component_labels], dim=1
        )
        self.update_from_component_tensor(
            new_tensor, coords, detach_stale_values, detach_new_values
        )

    def update_from_component_tensor(
        self,
        new_tensor: torch.Tensor,
        coords: Coords | None = None,
        detach_stale_values: bool = True,
        detach_new_values: bool = False,
    ) -> None:
        """Update the field from a component tensor of shape (n_points, n_components).

        If coords is a batch, only the batch rows are updated.
        """
        coords = self.coords if coords is None else coords

        expected_shape = (coords.n_points, len(self.component_labels))
        if new_tensor.shape != expected_shape:
            raise ValueError(
                f"Component tensor must have shape {expected_shape}, "
                f"got {new_tensor.shape}"
            )
        if new_tensor.device != self.device:
            raise ValueError(
                f"Component tensor is on {new_tensor.device}, expected {self.device}"
            )

        indices = self._indices(coords)
        if indices is not None and new_tensor.dtype != self.dtype:
            raise ValueError(
                f"Component tensor has dtype {new_tensor.dtype}, but the field "
                f"has dtype {self.dtype}"
            )

        if detach_new_values:
            new_tensor = new_tensor.detach()

        for i, label in enumerate(self.component_labels):
            if indices is None:
                setattr(self, label, new_tensor[:, i])
            else:
                component = getattr(self, label)
                if detach_stale_values:
                    component = component.detach()
                component[indices] = new_tensor[:, i]
                setattr(self, label, component)

    def update_from_tensor(
        self,
        new_tensor: torch.Tensor,
        coords: Coords | None = None,
        detach_stale_values: bool = True,
        detach_new_values: bool = False,
    ) -> None:
        """Update the field from a tensor of shape
        (n_points, n_geometric, ..., n_geometric)
        """
        coords = self.coords if coords is None else coords

        expected_shape = tensor_shape(coords, self.rank)
        if new_tensor.shape != expected_shape:
            raise ValueError(
                f"Tensor must have shape {expected_shape}, got {new_tensor.shape}"
            )

        self.update_from_component_tensor(
            new_tensor.reshape(coords.n_points, -1),
            coords,
            detach_stale_values,
            detach_new_values,
        )

    def _indices(self, coords: Coords | None) -> torch.Tensor | None:
        """Indices of coords within the field's coords, or None for all rows."""
        if coords is None:
            return None
        return coords.indices_in(self.coords)

    def _validate_inputs(self) -> None:
        if self.label in self.coords.coord_labels:
            raise ValueError(f"label '{self.label}' clashes with a coordinate label")

        dtypes = set()
        for label in self.component_labels:
            component = getattr(self, label)

            if not isinstance(component, torch.Tensor):
                raise TypeError(f"Field component {label} must be a torch.Tensor")

            if component.device != self.device:
                raise ValueError(
                    f"Field component {label} is on {component.device}, "
                    f"expected {self.device}"
                )

            dtypes.add(component.dtype)

            if component.shape != (self.coords.n_points,):
                raise ValueError(
                    f"Field component {label} must have shape matching "
                    f"coordinate points ({self.coords.n_points},), got "
                    f"shape {component.shape}"
                )

        if len(dtypes) > 1:
            raise ValueError(
                f"All field components must have the same dtype, got {dtypes}"
            )


def tensor_shape(coords: Coords, rank: int) -> tuple[int, ...]:
    """Shape of a rank-n tensor field at coords: (n_points, dim, ..., dim)."""
    return (coords.n_points,) + (len(coords.geometric_labels),) * rank


def generate_tensor_component_labels(
    geometric_labels: tuple[str, ...], rank: int
) -> tuple[str, ...]:
    """Generate labels for each component of a rank-n tensor field."""
    if rank < 0:
        raise ValueError(f"rank must be >= 0, got {rank}")
    if rank == 0:
        return ("value",)
    return tuple(
        "_".join(geometric_labels[i] for i in idx)
        for idx in product(range(len(geometric_labels)), repeat=rank)
    )


# Generated Field classes, by (rank, Coords class)
_field_classes: dict[tuple[int, type[Coords]], type[Field]] = {}


def make_field_dataclass(rank: int, coords_class: type[Coords]) -> type[Field]:
    """The Field class for fields of a given rank on coords of coords_class.

    Every field of the same rank on the same kind of coords shares one class.
    """
    key = (rank, coords_class)
    if key not in _field_classes:
        _field_classes[key] = _build_field_dataclass(rank, coords_class)
    return _field_classes[key]


def _build_field_dataclass(rank: int, coords_class: type[Coords]) -> type[Field]:
    component_labels = generate_tensor_component_labels(
        coords_class.geometric_labels, rank
    )
    check_labels_not_reserved(component_labels, Field)

    dataclass_fields: list[tuple[str, Any, Any]] = [
        ("label", str, field()),
        ("coords", Coords, field()),
        *(
            (label, torch.Tensor | None, field(default=None))
            for label in component_labels
        ),
    ]
    class_constants = {
        "coords_class": coords_class,
        "rank": rank,
        "component_labels": component_labels,
    }

    return make_dataclass(
        "Field",
        dataclass_fields,
        bases=(Field,),
        namespace=class_constants,
        eq=False,
        slots=True,
    )
